        // --- LOCALSTORAGE PERSISTENT AUTHENTICATION MANAGER ---
        class PersistentAuthManager {
            static USERS_KEY = 'breatheiq_users';
            static CURRENT_KEY = 'breatheiq_currentUser';

            static normalizeEmail(email) {
                return String(email || '').trim().toLowerCase();
            }

            static normalizeUsername(username) {
                return String(username || '').trim().toLowerCase();
            }

            static getUsers() {
                let users = [];
                try {
                    const raw = localStorage.getItem(this.USERS_KEY);
                    users = raw ? JSON.parse(raw) : [];
                    if (!Array.isArray(users)) users = [];
                } catch (error) {
                    users = [];
                }

                // Normalize older saved records without deleting existing registrations.
                users = users.filter(u => u && typeof u === 'object' && u.email).map(u => ({
                    ...u,
                    name: String(u.name || '').trim(),
                    username: this.normalizeUsername(u.username || ''),
                    email: this.normalizeEmail(u.email),
                    avatar: u.avatar || `https://api.dicebear.com/7.x/bottts/svg?seed=${encodeURIComponent(u.username || u.name || u.email)}`
                }));

                // Keep the original demo account available for the website's demo hint.
                if (!users.some(u => this.normalizeEmail(u.email) === 'demo@breatheiq.com')) {
                    users.unshift({
                        name: 'Demo Operator',
                        username: 'demo_operator',
                        email: 'demo@breatheiq.com',
                        password: 'password123',
                        avatar: 'https://api.dicebear.com/7.x/bottts/svg?seed=DemoOperator'
                    });
                }
                this.saveUsers(users);
                return users;
            }

            static saveUsers(users) {
                localStorage.setItem(this.USERS_KEY, JSON.stringify(users));
            }

            static register(name, username, email, password, avatar = null) {
                const users = this.getUsers();
                const cleanName = String(name || '').trim();
                const cleanUsername = this.normalizeUsername(username);
                const cleanEmail = this.normalizeEmail(email);

                if (!cleanName || !cleanUsername || !cleanEmail || !password) {
                    return { success: false, message: 'Please complete all registration fields.' };
                }
                if (users.some(u => this.normalizeEmail(u.email) === cleanEmail)) {
                    return { success: false, message: 'This email ID already exists. Please sign in or use another email ID.' };
                }
                if (users.some(u => this.normalizeUsername(u.username) === cleanUsername)) {
                    return { success: false, message: 'This username already exists. Please choose another username.' };
                }

                const newUser = {
                    name: cleanName,
                    username: cleanUsername,
                    email: cleanEmail,
                    password: password,
                    avatar: avatar || `https://api.dicebear.com/7.x/bottts/svg?seed=${encodeURIComponent(cleanUsername)}`
                };
                users.push(newUser);
                this.saveUsers(users);
                this.setCurrentUser(newUser);
                return { success: true, user: newUser };
            }

            static login(email, password) {
                const users = this.getUsers();
                const cleanEmail = this.normalizeEmail(email);
                const user = users.find(u => this.normalizeEmail(u.email) === cleanEmail && u.password === password);
                if (!user) return { success: false, message: 'Invalid email ID or password. Use the same email and password you registered with.' };
                this.setCurrentUser(user);
                return { success: true, user };
            }

            static getCurrentUser() {
                try {
                    const raw = localStorage.getItem(this.CURRENT_KEY);
                    if (!raw) return null;
                    const current = JSON.parse(raw);
                    if (!current || !current.email) return null;
                    // Always load the latest saved profile data for this email.
                    const saved = this.getUsers().find(u => this.normalizeEmail(u.email) === this.normalizeEmail(current.email));
                    return saved || current;
                } catch (error) {
                    return null;
                }
            }

            static setCurrentUser(user) {
                const safeUser = { ...user };
                localStorage.setItem(this.CURRENT_KEY, JSON.stringify(safeUser));
            }

            static updateUser(updatedUser) {
                const users = this.getUsers();
                const email = this.normalizeEmail(updatedUser.email);
                const username = this.normalizeUsername(updatedUser.username);
                let oldEmail = this.normalizeEmail(updatedUser.email);
                try {
                    const savedSession = JSON.parse(localStorage.getItem(this.CURRENT_KEY) || 'null');
                    if (savedSession && savedSession.email) oldEmail = this.normalizeEmail(savedSession.email);
                } catch (error) {}
                const existingEmail = users.find(u => this.normalizeEmail(u.email) === email && this.normalizeEmail(u.email) !== oldEmail);
                if (existingEmail) return { success: false, message: 'This email ID already exists on another account.' };
                const existingUsername = users.find(u => this.normalizeUsername(u.username) === username && this.normalizeEmail(u.email) !== oldEmail);
                if (existingUsername) return { success: false, message: 'This username is already used by another account.' };

                const index = users.findIndex(u => this.normalizeEmail(u.email) === oldEmail);
                if (index === -1) {
                    users.push({ ...updatedUser, email, username });
                } else {
                    users[index] = { ...users[index], ...updatedUser, email, username };
                }
                this.saveUsers(users);
                const saved = users.find(u => this.normalizeEmail(u.email) === email);
                this.setCurrentUser(saved);
                return { success: true, user: saved };
            }

            static logout() {
                localStorage.removeItem(this.CURRENT_KEY);
            }
        }

