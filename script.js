        function triggerHazardAlert(sensorKey, value, limit) {
            const s = SENSORS[sensorKey];
            const timeStr = new Date().toLocaleTimeString();
            
            if (s.lastAlertTime && (Date.now() - s.lastAlertTime < 10000)) return;
            s.lastAlertTime = Date.now();

            const msg = `ALERT: ${s.name} concentration (${value.toFixed(1)} ${s.unit}) exceeded threshold limit of ${limit} ${s.unit}!`;
            
            showToast(msg, "rose");

            if (document.getElementById('enable-browser-notif').checked && "Notification" in window && Notification.permission === "granted") {
                new Notification(`Breathe IQ Hazard Warning: ${s.name}`, {
                    body: msg,
                    icon: 'https://cdn-icons-png.flaticon.com/512/564/564619.png'
                });
            }

            if (document.getElementById('enable-audio-alarm').checked) {
                playAudioBeep();
            }

            state.alertHistory.push({
                time: timeStr,
                sensor: s.name,
                value: value.toFixed(1) + ' ' + s.unit,
                limit: limit + ' ' + s.unit,
                severity: 'CRITICAL BREACH'
            });
            if (state.alertHistory.length > 30) state.alertHistory.shift();
            renderAlertHistoryTable();
        }

        function playAudioBeep() {
            try {
                if (!state.audioCtx) state.audioCtx = new (window.AudioContext || window.webkitAudioContext)();
                const osc = state.audioCtx.createOscillator();
                const gain = state.audioCtx.createGain();
                osc.type = 'sawtooth';
                osc.frequency.setValueAtTime(880, state.audioCtx.currentTime);
                gain.gain.setValueAtTime(0.1, state.audioCtx.currentTime);
                osc.connect(gain);
                gain.connect(state.audioCtx.destination);
                osc.start();
                osc.stop(state.audioCtx.currentTime + 0.3);
            } catch(e) {}
        }

