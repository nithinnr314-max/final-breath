        function updateTelemetry() {
            if (state.isPaused) return;

            Object.keys(SENSORS).forEach(key => {
                let base = state.liveData[key];
                let delta = (Math.random() - 0.48) * 1.5;

                if (state.activeScenario === 'co_spike' && key === 'mq7') delta = Math.random() * 6 + 4;
                if (state.activeScenario === 'gas_leak' && (key === 'mq2' || key === 'mq6')) delta = Math.random() * 25 + 10;
                if (state.activeScenario === 'ammonia' && key === 'mq135') delta = Math.random() * 10 + 4;

                let newVal = Math.max(SENSORS[key].minVal, Math.min(SENSORS[key].maxVal, base + delta));
                state.liveData[key] = parseFloat(newVal.toFixed(1));

                const st = state.historyStats[key];
                st.min = Math.min(st.min, newVal);
                st.max = Math.max(st.max, newVal);
                st.sum += newVal;
                st.count += 1;
            });

            calculateOverallHazard();
            checkThresholdBreaches();
            refreshUIValues();
            appendLogEntry();
            updateCharts();
        }

        function calculateOverallHazard() {
            let totalPct = 0;
            let count = 0;
            Object.keys(SENSORS).forEach(k => {
                if (k === 'temp' || k === 'humidity') return;
                const s = SENSORS[k];
                totalPct += (state.liveData[k] / s.dangerLimit) * 100;
                count++;
            });

            const indexScore = Math.min(100, Math.round((totalPct / count) * 0.7));
            document.getElementById('overall-index-val').innerText = indexScore;
            document.getElementById('overall-index-bar').style.width = indexScore + '%';

            const badge = document.getElementById('overall-status-badge');
            if (indexScore < 30) {
                badge.className = "px-3 py-1 rounded-full text-xs font-bold bg-emerald-500/20 text-emerald-600 dark:text-emerald-400 border border-emerald-500/30";
                badge.innerText = "SAFE / CLEAN";
            } else if (indexScore < 60) {
                badge.className = "px-3 py-1 rounded-full text-xs font-bold bg-amber-500/20 text-amber-600 dark:text-amber-400 border border-amber-500/30";
                badge.innerText = "MODERATE WARNING";
            } else {
                badge.className = "px-3 py-1 rounded-full text-xs font-bold bg-rose-500/20 text-rose-600 dark:text-rose-400 border border-rose-500/30 animate-pulse";
                badge.innerText = "HAZARDOUS BREACH";
            }
        }

